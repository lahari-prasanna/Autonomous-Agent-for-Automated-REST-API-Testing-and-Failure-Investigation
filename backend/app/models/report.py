"""
DiagnosticReport Database Model (Phase 5A).
Stores validated DiagnosticReport snapshots and pre-rendered safe Markdown reports.
"""

from __future__ import annotations

from typing import TYPE_CHECKING, Any, Optional

from sqlalchemy import ForeignKey, String, Text
from sqlalchemy.orm import Mapped, mapped_column, relationship

from backend.app.models.base import Base, PortableJSON, TimestampMixin, UUIDMixin

if TYPE_CHECKING:
    from backend.app.models.run import AgentRun


class DiagnosticReportModel(Base, UUIDMixin, TimestampMixin):
    """
    Persistent store for completed DiagnosticReport snapshots generated by DiagnosticReportGenerator.
    """
    __tablename__ = "diagnostic_reports"

    run_id: Mapped[str] = mapped_column(
        String(36),
        ForeignKey("agent_runs.id", ondelete="CASCADE"),
        nullable=False,
        unique=True,
        index=True,
        doc="Associated agent run session ID (1-to-1 relationship)",
    )
    report_id: Mapped[str] = mapped_column(
        String(64),
        nullable=False,
        index=True,
        doc="Canonical report ID string (e.g. rep_b6f7b85e1497)",
    )
    api_title: Mapped[str] = mapped_column(
        String(255),
        nullable=False,
        doc="Target API specification title",
    )
    api_version: Mapped[str] = mapped_column(
        String(50),
        nullable=False,
        doc="Target API specification version",
    )
    base_url: Mapped[Optional[str]] = mapped_column(
        String(1024),
        nullable=True,
        doc="Base URL against which tests were executed",
    )
    summary_data: Mapped[Any] = mapped_column(
        PortableJSON,
        nullable=False,
        doc="Serialized RunSummaryStatistics snapshot (pass rate, totals, variation metrics)",
    )
    operations_data: Mapped[Any] = mapped_column(
        PortableJSON,
        nullable=False,
        doc="Serialized list of OperationRunRecord snapshots",
    )
    global_remediation_summary: Mapped[Optional[Any]] = mapped_column(
        PortableJSON,
        nullable=True,
        doc="Top-level remediation recommendations",
    )
    markdown_rendered: Mapped[Optional[str]] = mapped_column(
        Text,
        nullable=True,
        doc="Pre-rendered safe Markdown report from DiagnosticReportGenerator.to_markdown()",
    )

    # Relationships
    run: Mapped[AgentRun] = relationship(
        "AgentRun",
        back_populates="report",
        lazy="selectin",
    )

    def __repr__(self) -> str:
        return f"<DiagnosticReportModel id={self.id} report_id='{self.report_id}' run_id={self.run_id}>"
